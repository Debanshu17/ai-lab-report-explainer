"""Input validation for uploaded lab report PDFs.

Enforces file size, page limits, magic bytes, and detects scanned/image-only PDFs.
"""

from __future__ import annotations

import io
from pathlib import Path
from typing import Union
from pydantic import BaseModel, Field

import pymupdf

from src.config import settings, get_logger

logger = get_logger(__name__)


class ValidationError(Exception):
    """User-facing validation exception for PDF uploads."""

    def __init__(self, message: str, code: str = "INVALID_PDF"):
        super().__init__(message)
        self.message = message
        self.code = code


class ValidationResult(BaseModel):
    """Structured result of PDF validation."""

    is_valid: bool
    num_pages: int
    file_size_bytes: int
    total_characters: int
    is_scanned: bool = False
    message: str = "PDF validation passed."


def validate_pdf_bytes(
    pdf_bytes: bytes,
    max_size_mb: int = settings.MAX_FILE_SIZE_MB,
    max_pages: int = settings.MAX_PDF_PAGES,
    min_char_threshold: int = 30,
) -> ValidationResult:
    """Validate raw PDF bytes before any downstream processing.

    Raises:
        ValidationError: If the PDF violates size, page count, or is a scanned image.
    """
    size_bytes = len(pdf_bytes)
    max_bytes = max_size_mb * 1024 * 1024

    if size_bytes == 0:
        raise ValidationError("Uploaded file is completely empty (0 bytes).", code="EMPTY_FILE")

    if size_bytes > max_bytes:
        raise ValidationError(
            f"File size ({size_bytes / (1024 * 1024):.2f} MB) exceeds maximum limit of {max_size_mb} MB.",
            code="FILE_TOO_LARGE",
        )

    # Magic byte check
    if not pdf_bytes.startswith(b"%PDF-"):
        raise ValidationError("Invalid file format. File does not appear to be a valid PDF.", code="NOT_A_PDF")

    try:
        doc = pymupdf.open(stream=pdf_bytes, filetype="pdf")
    except Exception as exc:
        raise ValidationError(f"Could not open or decrypt PDF document: {exc}", code="CORRUPT_PDF") from exc

    try:
        num_pages = len(doc)
        if num_pages == 0:
            raise ValidationError("PDF contains 0 pages.", code="NO_PAGES")

        if num_pages > max_pages:
            raise ValidationError(
                f"PDF has {num_pages} pages, which exceeds the maximum limit of {max_pages} pages.",
                code="TOO_MANY_PAGES",
            )

        total_chars = 0
        for page in doc:
            text = page.get_text()
            total_chars += len(text.strip())

        # Scanned PDF check: image-only PDFs will yield virtually 0 text
        if total_chars < min_char_threshold:
            raise ValidationError(
                "Scanned reports are not supported yet. Please upload a digital PDF report generated by your laboratory.",
                code="SCANNED_PDF_NOT_SUPPORTED",
            )

        return ValidationResult(
            is_valid=True,
            num_pages=num_pages,
            file_size_bytes=size_bytes,
            total_characters=total_chars,
            is_scanned=False,
            message="PDF validated successfully.",
        )
    finally:
        doc.close()


def validate_pdf_file(
    file_path: Union[Path, str],
    max_size_mb: int = settings.MAX_FILE_SIZE_MB,
    max_pages: int = settings.MAX_PDF_PAGES,
) -> ValidationResult:
    """Validate a PDF file on disk."""
    path = Path(file_path)
    if not path.is_file():
        raise ValidationError(f"File not found: {path}", code="FILE_NOT_FOUND")
    return validate_pdf_bytes(path.read_bytes(), max_size_mb, max_pages)
